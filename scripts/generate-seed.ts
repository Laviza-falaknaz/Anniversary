// Generates supabase/seed.sql from the content modules.
//   npm run seed        → writes supabase/seed.sql (idempotent: safe to run repeatedly)
import { writeFileSync } from 'node:fs'
import { LETTERS } from '../src/content/letters'
import { UNLOCK_SCHEDULE } from '../src/content/schedule'
import { REWARDS } from '../src/content/rewards'
import { PLANNER_OPTIONS } from '../src/content/planner'
import { SITE } from '../src/content/site'
import { zonedToEpoch } from '../src/lib/time'

const q = (s: string) => {
  if (s.includes('$anniv$')) throw new Error('Content may not contain the sequence $anniv$')
  return `$anniv$${s}$anniv$`
}
const iso = (ms: number) => new Date(ms).toISOString()

export function buildSeed(): { sql: string; placeholders: number } {
  const out: string[] = ['-- GENERATED by `npm run seed` from src/content/*. Do not edit by hand.', 'begin;', '']
  const dayStart = zonedToEpoch(SITE.anniversaryDate, '00:00', SITE.timezone)

  LETTERS.forEach((l, i) => {
    const when = UNLOCK_SCHEDULE[l.slug]
    if (!when) throw new Error(`No unlock time for letter "${l.slug}" in src/content/schedule.ts`)
    // 'immediate' never lands in the future: it is the earlier of "now" and the start of the day.
    const unlock = when === 'immediate'
      ? `least(now(), '${iso(dayStart)}'::timestamptz)`
      : `'${iso(zonedToEpoch(SITE.anniversaryDate, when, SITE.timezone))}'::timestamptz`
    out.push(
      `insert into anniversary_messages (slug, position, purpose, teaser, title, body, unlock_at) values (` +
      `${q(l.slug)}, ${i + 1}, ${q(l.purpose)}, ${q(l.teaser)}, ${q(l.title)}, ${q(l.body)}, ${unlock})\n` +
      `on conflict (slug) do update set position = excluded.position, purpose = excluded.purpose, teaser = excluded.teaser,\n` +
      `  title = excluded.title, body = excluded.body, unlock_at = excluded.unlock_at, updated_at = now();`,
    )
  })
  out.push('')
  REWARDS.forEach((r, i) => {
    out.push(
      `insert into gift_rewards (key, label, description, kind, weight, sort_order, active) values (` +
      `${q(r.key)}, ${q(r.label)}, ${q(r.description)}, ${q(r.kind)}, ${r.weight}, ${i}, true)\n` +
      `on conflict (key) do update set label = excluded.label, description = excluded.description, kind = excluded.kind,\n` +
      `  weight = excluded.weight, sort_order = excluded.sort_order, active = true;`,
    )
  })
  out.push('')
  PLANNER_OPTIONS.forEach((o, i) => {
    out.push(
      `insert into planner_options (key, category, label, description, sort_order, active) values (` +
      `${q(o.key)}, ${q(o.category)}, ${q(o.label)}, ${q(o.description)}, ${i}, true)\n` +
      `on conflict (key) do update set category = excluded.category, label = excluded.label,\n` +
      `  description = excluded.description, sort_order = excluded.sort_order, active = true;`,
    )
  })
  out.push('', 'commit;', '')
  const placeholders = LETTERS.reduce((n, l) => n + (l.body.match(/\[\[/g)?.length ?? 0), 0)
  return { sql: out.join('\n'), placeholders }
}

if (process.argv[1] && process.argv[1].endsWith('generate-seed.ts')) {
  const { sql, placeholders } = buildSeed()
  writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
  console.log(`Wrote supabase/seed.sql (${LETTERS.length} letters, ${REWARDS.length} rewards, ${PLANNER_OPTIONS.length} planner options).`)
  if (placeholders) console.log(`Heads up: ${placeholders} [[ADD: …]] placeholder(s) remain in the letters.`)
}
